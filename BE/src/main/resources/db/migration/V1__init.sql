    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT,
    user_email_hash VARCHAR(255),
    action          VARCHAR(50)   NOT NULL,
    entity_type     VARCHAR(50),
    entity_id       BIGINT,
    entity_name     VARCHAR(255),
    ip_address      VARCHAR(50),
    changes         TEXT,
    metadata        TEXT,
